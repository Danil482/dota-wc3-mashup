"""Generate build/mock_natives.lua: a stub WC3 API built from common.j and Blizzard.j.

Every native and Blizzard.j function becomes a Lua stub returning a default for
its declared return type, so a misspelled native fails offline exactly like a
nil call would in game. Constants and bj_ globals get their real values where
they are simple literals.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JASS = os.path.join(ROOT, "research", "jass")

FUNC_RE = re.compile(r"^\s*(?:constant\s+)?(native|function)\s+(\w+)\s+takes\s+(.+?)\s+returns\s+(\w+)", re.M)
CONST_RE = re.compile(r"^\s*constant\s+(\w+)\s+(\w+)\s*=\s*(.+?)\s*(?://.*)?$", re.M)
GLOBAL_RE = re.compile(r"^\s*(\w+)\s+(?:array\s+)?(\w+)\s*(?:=\s*(.+?))?\s*(?://.*)?$", re.M)

PRIMITIVE_DEFAULT = {"integer": "0", "real": "0.0", "boolean": "false", "string": '""', "code": "nil", "nothing": None}


def fourcc(s):
    v = 0
    for ch in s:
        v = v * 256 + ord(ch)
    return v


def literal(expr):
    expr = expr.strip()
    m = re.fullmatch(r"'(.{4})'", expr)
    if m:
        return str(fourcc(m.group(1)))
    m = re.fullmatch(r"Convert\w+\((-?\d+)\)", expr)
    if m:
        return f"__const({m.group(1)})"
    m = re.fullmatch(r"Convert\w+\('(.{4})'\)", expr)
    if m:
        return f"__const({fourcc(m.group(1))})"
    if re.fullmatch(r"-?\d+", expr) or re.fullmatch(r"-?\d*\.\d+", expr) or re.fullmatch(r"-?\d+\.\d*", expr):
        return expr if not expr.endswith(".") else expr + "0"
    if re.fullmatch(r"0x[0-9a-fA-F]+", expr) or re.fullmatch(r"\$[0-9a-fA-F]+", expr):
        return str(int(expr.replace("$", "0x"), 16))
    if expr in ("true", "false"):
        return expr
    if re.fullmatch(r'"[^"]*"', expr):
        return expr
    if re.fullmatch(r"\w+", expr):
        return expr  # reference to another constant
    return None


def main(out):
    lines = ["-- generated by tools/gen_mock.py", "__mock = {calls = {}}",
             "local H = {__index = function() return nil end}",
             "function __handle(t) return setmetatable({__type = t}, H) end",
             "function __const(n) return setmetatable({__const = n}, H) end"]
    seen = set()
    for fname in ("common.j", "blizzard.j"):
        with open(os.path.join(JASS, fname), encoding="utf-8", errors="replace") as f:
            text = f.read()
        # globals blocks: constants and bj_ variables
        for block in re.findall(r"^globals\s*$(.*?)^endglobals", text, re.S | re.M):
            for m in CONST_RE.finditer(block):
                _, name, expr = m.groups()
                val = literal(expr)
                if val is not None and name not in seen:
                    seen.add(name)
                    lines.append(f"{name} = {val}")
            for m in GLOBAL_RE.finditer(block):
                typ, name, expr = m.groups()
                if typ in ("constant", "endglobals") or name in seen:
                    continue
                val = literal(expr) if expr else PRIMITIVE_DEFAULT.get(typ, "nil")
                if val is None:
                    val = "nil"
                seen.add(name)
                lines.append(f"{name} = {val}")
        for m in FUNC_RE.finditer(text):
            kind, name, _, ret = m.groups()
            if name in seen:
                continue
            seen.add(name)
            if ret == "nothing":
                body = ""
            elif ret in PRIMITIVE_DEFAULT:
                body = f"return {PRIMITIVE_DEFAULT[ret]}"
            else:
                body = f'return __handle("{ret}")'
            lines.append(f"function {name}(...) __mock.calls.{name} = (__mock.calls.{name} or 0) + 1 {body} end")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"mock: {len(seen)} names")


if __name__ == "__main__":
    main(sys.argv[1])
